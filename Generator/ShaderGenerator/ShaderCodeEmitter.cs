using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Apotheosis.Generator.AssetPathGenerator;

namespace Apotheosis.Generator.ShaderGenerator;

/// <summary>
/// 根据 <c>.xnb</c> 解析出的参数表，为每个着色器生成零分配的强类型 <c>readonly struct XxxShader : IShader</c> 包装类，
/// 内置静态参数名数组、O(1) 槽位索引常量、强类型 Setter、Technique/Pass 常量以及到 <c>ShaderHandle</c> 的隐式转换。
/// </summary>
internal static class ShaderCodeEmitter
{
    private const string ShaderHandleType = "global::Apotheosis.Runtime.Rendering.Shaders.ShaderHandle";
    private const string IShaderType = "global::Apotheosis.Runtime.Rendering.Shaders.IShader";
    private const string RenderManagerType = "global::Apotheosis.Runtime.Rendering.RenderManager";
    private const string EffectType = "global::Microsoft.Xna.Framework.Graphics.Effect";
    private const string MatrixType = "global::Microsoft.Xna.Framework.Matrix";
    private const string Vector2Type = "global::Microsoft.Xna.Framework.Vector2";
    private const string Vector3Type = "global::Microsoft.Xna.Framework.Vector3";
    private const string Vector4Type = "global::Microsoft.Xna.Framework.Vector4";
    private const string ColorType = "global::Microsoft.Xna.Framework.Color";
    private const string TextureType = "global::Microsoft.Xna.Framework.Graphics.Texture";

    // 已由 IShader 全局通用接口直连管理的内置参数（不重复占用自定义槽位数组）
    private static readonly HashSet<string> GlobalBuiltInParamNames = new(StringComparer.Ordinal)
    {
        "uTime",
        "uTransformMatrix",
        "uScreenResolution",
        "uZoom",
    };

    private sealed class GeneratedShaderInfo
    {
        public AssetRecord Asset { get; }
        public string StructNameCore { get; }
        public ShaderMetadataRecord? Metadata { get; }

        public GeneratedShaderInfo(
            AssetRecord asset,
            string structNameCore,
            ShaderMetadataRecord? metadata)
        {
            Asset = asset;
            StructNameCore = structNameCore;
            Metadata = metadata;
        }
    }

    public static Dictionary<string, string> ResolveShaderTypes(
        string rootNamespace,
        EquatableArray<AssetRecord> deduplicatedAssets)
    {
        string shaderNamespace = GetShaderNamespace(rootNamespace);
        var entries = ResolveShaderEntries(deduplicatedAssets);
        var shaderTypeByPath = new Dictionary<string, string>(entries.Count, StringComparer.OrdinalIgnoreCase);

        for (int i = 0; i < entries.Count; i++)
        {
            var (asset, structNameCore) = entries[i];
            string escapedStruct = AssetPathResolver.EscapeIfKeyword(structNameCore);
            shaderTypeByPath[asset.ModAssetPath] = $"global::{shaderNamespace}.{escapedStruct}";
        }

        return shaderTypeByPath;
    }

    public static (string Source, int ShaderCount, List<string> MissingMetadataPaths) Emit(
        string rootNamespace,
        EquatableArray<AssetRecord> deduplicatedAssets,
        EquatableArray<ShaderMetadataRecord> metadataRecords)
    {
        string shaderNamespace = GetShaderNamespace(rootNamespace);
        var entries = ResolveShaderEntries(deduplicatedAssets);

        var missingMetadataPaths = new List<string>();
        if (entries.Count == 0)
            return (string.Empty, 0, missingMetadataPaths);

        var metaByPath = new Dictionary<string, ShaderMetadataRecord>(StringComparer.OrdinalIgnoreCase);
        for (int i = 0; i < metadataRecords.Length; i++)
        {
            var meta = metadataRecords[i];
            metaByPath[meta.ModAssetPath] = meta;
        }

        var infos = new List<GeneratedShaderInfo>(entries.Count);
        for (int i = 0; i < entries.Count; i++)
        {
            var (asset, structNameCore) = entries[i];
            if (!metaByPath.TryGetValue(asset.ModAssetPath, out var meta))
                missingMetadataPaths.Add(asset.ModAssetPath);

            infos.Add(new GeneratedShaderInfo(asset, structNameCore, meta));
        }

        var sb = new StringBuilder(4096);
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.Append("namespace ").AppendLine(shaderNamespace);
        sb.AppendLine("{");

        for (int i = 0; i < infos.Count; i++)
        {
            if (i > 0)
                sb.AppendLine();

            EmitShaderStruct(sb, infos[i]);
        }

        sb.AppendLine("}");
        return (sb.ToString(), infos.Count, missingMetadataPaths);
    }

    private static string GetShaderNamespace(string rootNamespace)
    {
        string ns = string.IsNullOrWhiteSpace(rootNamespace) ? "Apotheosis" : rootNamespace;
        return ns + ".Shaders";
    }

    private static List<(AssetRecord Asset, string StructNameCore)> ResolveShaderEntries(
        EquatableArray<AssetRecord> deduplicatedAssets)
    {
        var effectAssets = deduplicatedAssets
            .Where(static a => a.Kind == AssetKind.Effect)
            .OrderBy(static a => a.ModAssetPath, StringComparer.OrdinalIgnoreCase)
            .ThenBy(static a => a.ModAssetPath, StringComparer.Ordinal)
            .ToList();

        var usedTypeNames = new HashSet<string>(StringComparer.Ordinal);
        var entries = new List<(AssetRecord Asset, string StructNameCore)>(effectAssets.Count);

        for (int i = 0; i < effectAssets.Count; i++)
        {
            var asset = effectAssets[i];
            string structNameCore = ResolveUniqueShaderStructName(asset, usedTypeNames);
            entries.Add((asset, structNameCore));
        }

        return entries;
    }

    private static readonly HashSet<string> ShaderRootDirNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "Effect",
        "Effects",
        "Shader",
        "Shaders",
    };

    private static string ResolveUniqueShaderStructName(AssetRecord asset, HashSet<string> usedNames)
    {
        string baseCore = AssetPathResolver.SanitizeIdentifierCore(asset.FileNameWithoutExtension);
        string shaderSuffix = baseCore.EndsWith("Shader", StringComparison.Ordinal) ? baseCore : baseCore + "Shader";

        // 确定性子目录前缀：正向定位最外层 Shader/Effect 根目录；
        // 位于 Shaders/ 根目录下的直接生成 XxxShader；
        // 位于 Shaders/SubDir/... 下的固定带子目录前缀 SubDir_XxxShader（含 Effects 等子目录），避免命名折叠与漂移。
        int shaderRootIndex = -1;
        for (int i = 0; i < asset.DirectorySegments.Length; i++)
        {
            if (ShaderRootDirNames.Contains(asset.DirectorySegments[i]))
            {
                shaderRootIndex = i;
                break;
            }
        }

        string candidate;
        if (shaderRootIndex >= 0 && shaderRootIndex + 1 < asset.DirectorySegments.Length)
        {
            var sb = new StringBuilder();
            for (int i = shaderRootIndex + 1; i < asset.DirectorySegments.Length; i++)
            {
                sb.Append(AssetPathResolver.SanitizeIdentifierCore(asset.DirectorySegments[i])).Append('_');
            }
            sb.Append(shaderSuffix);
            candidate = sb.ToString();
        }
        else
        {
            candidate = shaderSuffix;
        }

        if (usedNames.Add(candidate))
            return candidate;

        int suffix = 2;
        while (true)
        {
            string fallback = candidate + "_" + suffix;
            if (usedNames.Add(fallback))
                return fallback;
            suffix++;
        }
    }

    private static void EmitShaderStruct(StringBuilder sb, GeneratedShaderInfo info)
    {
        string typeIdent = AssetPathResolver.EscapeIfKeyword(info.StructNameCore);
        string escapedPath = info.Asset.ModAssetPath.Replace("\\", "\\\\").Replace("\"", "\\\"");

        var customParams = new List<(ShaderParamDescriptor Param, ParamBinding Binding)>();
        if (info.Metadata is not null)
        {
            for (int i = 0; i < info.Metadata.Parameters.Length; i++)
            {
                var p = info.Metadata.Parameters[i];
                if (string.IsNullOrWhiteSpace(p.Name) || GlobalBuiltInParamNames.Contains(p.Name))
                    continue;

                if (TryMapBinding(p, out var binding))
                    customParams.Add((p, binding));
            }
        }

        sb.AppendLine($"    /// <summary>自动生成的强类型着色器包装（资源路径：<c>{EscapeXml(info.Asset.ModAssetPath)}</c>）。</summary>");
        sb.AppendLine($"    public readonly struct {typeIdent} : {IShaderType}, global::System.IEquatable<{typeIdent}>");
        sb.AppendLine("    {");
        sb.AppendLine($"        public const string AssetPath = \"{escapedPath}\";");

        var usedMembers = new HashSet<string>(StringComparer.Ordinal)
        {
            info.StructNameCore,
            "AssetPath",
            "ParameterNames",
            "Handle",
            "IsValid",
            "IsReady",
            "RawEffect",
            "SetTime",
            "SetTransformMatrix",
            "SetScreenResolution",
            "SetZoom",
            "Apply",
            "PrepareForSpriteBatch",
            "Equals",
            "GetHashCode",
            "ToString",
        };

        var slotConstNames = new List<string>(customParams.Count);
        if (customParams.Count > 0)
        {
            sb.AppendLine();
            for (int i = 0; i < customParams.Count; i++)
            {
                string paramName = customParams[i].Param.Name;
                string slotConst = ReserveUniqueMember("Slot_" + AssetPathResolver.SanitizeIdentifierCore(paramName), usedMembers);
                slotConstNames.Add(slotConst);
                sb.AppendLine($"        public const int {slotConst} = {i};");
            }
        }

        sb.AppendLine();
        if (customParams.Count == 0)
        {
            sb.AppendLine("        internal static readonly string[] ParameterNames = global::System.Array.Empty<string>();");
        }
        else
        {
            sb.AppendLine("        internal static readonly string[] ParameterNames = new string[]");
            sb.AppendLine("        {");
            for (int i = 0; i < customParams.Count; i++)
            {
                string escapedParamName = customParams[i].Param.Name.Replace("\\", "\\\\").Replace("\"", "\\\"");
                sb.AppendLine($"            \"{escapedParamName}\",");
            }
            sb.AppendLine("        };");
        }

        if (info.Metadata is not null && info.Metadata.Techniques.Length > 0)
        {
            sb.AppendLine();
            for (int t = 0; t < info.Metadata.Techniques.Length; t++)
            {
                var tech = info.Metadata.Techniques[t];
                string techSuffix = string.IsNullOrWhiteSpace(tech.Name)
                    ? t.ToString()
                    : AssetPathResolver.SanitizeIdentifierCore(tech.Name);
                string techConst = ReserveUniqueMember("Technique_" + techSuffix, usedMembers);
                sb.AppendLine($"        public const int {techConst} = {t};");

                for (int p = 0; p < tech.Passes.Length; p++)
                {
                    string passSuffix = string.IsNullOrWhiteSpace(tech.Passes[p])
                        ? p.ToString()
                        : AssetPathResolver.SanitizeIdentifierCore(tech.Passes[p]);
                    string passConst = ReserveUniqueMember($"Pass_{techSuffix}_{passSuffix}", usedMembers);
                    sb.AppendLine($"        public const int {passConst} = {p};");
                }
            }
        }

        sb.AppendLine();
        sb.AppendLine($"        public {ShaderHandleType} Handle {{ get; }}");
        sb.AppendLine();
        sb.AppendLine($"        internal {typeIdent}({ShaderHandleType} handle) => Handle = handle;");
        sb.AppendLine();
        sb.AppendLine("        public bool IsValid => Handle.IsValid;");
        sb.AppendLine();
        sb.AppendLine($"        public bool IsReady => {RenderManagerType}.Shaders.TryGet(Handle, out var shader) && shader.IsReady;");
        sb.AppendLine();
        sb.AppendLine($"        public {EffectType}? RawEffect => {RenderManagerType}.Shaders.TryGet(Handle, out var shader) ? shader.RawEffect : null;");

        sb.AppendLine();
        sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        sb.AppendLine("        public void SetTime(float time)");
        sb.AppendLine("        {");
        sb.AppendLine($"            if ({RenderManagerType}.Shaders.TryGet(Handle, out var shader))");
        sb.AppendLine("                shader.SetTime(time);");
        sb.AppendLine("        }");

        sb.AppendLine();
        sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        sb.AppendLine($"        public void SetTransformMatrix(in {MatrixType} matrix)");
        sb.AppendLine("        {");
        sb.AppendLine($"            if ({RenderManagerType}.Shaders.TryGet(Handle, out var shader))");
        sb.AppendLine("                shader.SetTransformMatrix(in matrix);");
        sb.AppendLine("        }");

        sb.AppendLine();
        sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        sb.AppendLine($"        public void SetScreenResolution({Vector2Type} resolution)");
        sb.AppendLine("        {");
        sb.AppendLine($"            if ({RenderManagerType}.Shaders.TryGet(Handle, out var shader))");
        sb.AppendLine("                shader.SetScreenResolution(resolution);");
        sb.AppendLine("        }");

        sb.AppendLine();
        sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        sb.AppendLine($"        public void SetZoom({Vector2Type} zoom)");
        sb.AppendLine("        {");
        sb.AppendLine($"            if ({RenderManagerType}.Shaders.TryGet(Handle, out var shader))");
        sb.AppendLine("                shader.SetZoom(zoom);");
        sb.AppendLine("        }");

        sb.AppendLine();
        sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
        sb.AppendLine("        public void Apply(int techniqueIndex = 0, int passIndex = 0)");
        sb.AppendLine("        {");
        sb.AppendLine($"            if ({RenderManagerType}.Shaders.TryGet(Handle, out var shader))");
        sb.AppendLine("                shader.Apply(techniqueIndex, passIndex);");
        sb.AppendLine("        }");

        sb.AppendLine();
        sb.AppendLine($"        public {EffectType}? PrepareForSpriteBatch(int techniqueIndex = 0)");
        sb.AppendLine($"            => {RenderManagerType}.Shaders.TryGet(Handle, out var shader) ? shader.PrepareForSpriteBatch(techniqueIndex) : null;");

        for (int i = 0; i < customParams.Count; i++)
        {
            var (param, binding) = customParams[i];
            string slotConst = slotConstNames[i];
            string methodName = ReserveUniqueMember(BuildSetterMethodName(param.Name), usedMembers);

            sb.AppendLine();
            sb.AppendLine($"        /// <summary>设置着色器参数 <c>{EscapeXml(param.Name)}</c>。</summary>");
            sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
            sb.AppendLine($"        public {typeIdent} {methodName}({binding.ParameterSignature})");
            sb.AppendLine("        {");
            sb.AppendLine($"            if ({RenderManagerType}.Shaders.TryGet(Handle, out var shader))");
            sb.AppendLine($"                shader.{binding.ManagedSetterCall(slotConst)};");
            sb.AppendLine("            return this;");
            sb.AppendLine("        }");

            if (binding.HasColorOverload)
            {
                sb.AppendLine();
                sb.AppendLine($"        /// <summary>以 <see cref=\"{ColorType}\"/> 设置着色器参数 <c>{EscapeXml(param.Name)}</c>。</summary>");
                sb.AppendLine("        [global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
                sb.AppendLine($"        public {typeIdent} {methodName}({ColorType} value)");
                sb.AppendLine("        {");
                sb.AppendLine($"            if ({RenderManagerType}.Shaders.TryGet(Handle, out var shader))");
                sb.AppendLine($"                shader.SetColor({slotConst}, value);");
                sb.AppendLine("            return this;");
                sb.AppendLine("        }");
            }
        }

        sb.AppendLine();
        sb.AppendLine($"        public static implicit operator {ShaderHandleType}({typeIdent} shader) => shader.Handle;");
        sb.AppendLine();
        sb.AppendLine($"        public bool Equals({typeIdent} other) => Handle.Equals(other.Handle);");
        sb.AppendLine($"        public override bool Equals(object? obj) => obj is {typeIdent} other && Equals(other);");
        sb.AppendLine("        public override int GetHashCode() => Handle.GetHashCode();");
        sb.AppendLine($"        public static bool operator ==({typeIdent} left, {typeIdent} right) => left.Equals(right);");
        sb.AppendLine($"        public static bool operator !=({typeIdent} left, {typeIdent} right) => !left.Equals(right);");
        sb.AppendLine("    }");
    }

    private readonly struct ParamBinding
    {
        public string ParameterSignature { get; }
        public string ManagedMethodName { get; }
        public bool PassByIn { get; }
        public bool HasColorOverload { get; }

        public ParamBinding(string parameterSignature, string managedMethodName, bool passByIn = false, bool hasColorOverload = false)
        {
            ParameterSignature = parameterSignature;
            ManagedMethodName = managedMethodName;
            PassByIn = passByIn;
            HasColorOverload = hasColorOverload;
        }

        public string ManagedSetterCall(string slotConst)
            => PassByIn ? $"{ManagedMethodName}({slotConst}, in value)" : $"{ManagedMethodName}({slotConst}, value)";
    }

    private enum D3dxParameterType : uint
    {
        Bool = 1,
        Int = 2,
        Float = 3,
        Texture = 5,
        Texture1D = 6,
        Texture2D = 7,
        Texture3D = 8,
        TextureCube = 9,
    }

    private enum D3dxParameterClass : uint
    {
        Scalar = 0,
        Vector = 1,
        MatrixRows = 2,
        MatrixColumns = 3,
    }

    private static bool TryMapBinding(ShaderParamDescriptor p, out ParamBinding binding)
    {
        bool isArray = p.Elements > 0;
        var paramType = (D3dxParameterType)p.ParamType;
        var paramClass = (D3dxParameterClass)p.ParamClass;

        switch (paramType)
        {
            case D3dxParameterType.Bool when paramClass == D3dxParameterClass.Scalar && !isArray:
                binding = new ParamBinding("bool value", "SetBool");
                return true;

            case D3dxParameterType.Int when paramClass == D3dxParameterClass.Scalar && !isArray:
                binding = new ParamBinding("int value", "SetInt");
                return true;

            case D3dxParameterType.Float when paramClass == D3dxParameterClass.Scalar:
                binding = isArray
                    ? new ParamBinding("float[] value", "SetFloatArray")
                    : new ParamBinding("float value", "SetFloat");
                return true;

            case D3dxParameterType.Float when paramClass == D3dxParameterClass.Vector:
                return p.Columns switch
                {
                    2 => ReturnBinding(isArray
                        ? new ParamBinding($"{Vector2Type}[] value", "SetVector2Array")
                        : new ParamBinding($"{Vector2Type} value", "SetVector2"), out binding),
                    3 => ReturnBinding(isArray
                        ? new ParamBinding($"{Vector3Type}[] value", "SetVector3Array")
                        : new ParamBinding($"{Vector3Type} value", "SetVector3"), out binding),
                    4 => ReturnBinding(isArray
                        ? new ParamBinding($"{Vector4Type}[] value", "SetVector4Array")
                        : new ParamBinding($"{Vector4Type} value", "SetVector4", hasColorOverload: true), out binding),
                    _ => ReturnEmpty(out binding),
                };

            case D3dxParameterType.Float
                when paramClass is D3dxParameterClass.MatrixRows or D3dxParameterClass.MatrixColumns
                     && p.Rows == 4 && p.Columns == 4:
                binding = isArray
                    ? new ParamBinding($"{MatrixType}[] value", "SetMatrixArray")
                    : new ParamBinding($"in {MatrixType} value", "SetMatrix", passByIn: true);
                return true;

            case >= D3dxParameterType.Texture and <= D3dxParameterType.TextureCube when !isArray:
                binding = new ParamBinding($"{TextureType}? value", "SetTexture");
                return true;

            default:
                binding = default;
                return false;
        }
    }

    private static bool ReturnBinding(ParamBinding value, out ParamBinding binding)
    {
        binding = value;
        return true;
    }

    private static bool ReturnEmpty(out ParamBinding binding)
    {
        binding = default;
        return false;
    }

    private static string BuildSetterMethodName(string rawParamName)
    {
        string clean = AssetPathResolver.SanitizeIdentifierCore(rawParamName);
        if (clean.Length >= 2 && clean[0] == 'u' && char.IsUpper(clean[1]))
            clean = clean.Substring(1);
        else if (clean.Length > 0 && char.IsLower(clean[0]))
            clean = char.ToUpperInvariant(clean[0]) + clean.Substring(1);

        return "Set" + clean;
    }

    private static string ReserveUniqueMember(string baseName, HashSet<string> usedMembers)
    {
        if (usedMembers.Add(baseName))
            return baseName;

        int suffix = 2;
        while (true)
        {
            string candidate = baseName + "_" + suffix;
            if (usedMembers.Add(candidate))
                return candidate;
            suffix++;
        }
    }

    private static string EscapeXml(string value)
    {
        return value
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }
}
