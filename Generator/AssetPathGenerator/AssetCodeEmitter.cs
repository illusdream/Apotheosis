using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Apotheosis.Generator.AssetPathGenerator;

internal static class AssetCodeEmitter
{
    private const string TextureType = "global::ReLogic.Content.Asset<global::Microsoft.Xna.Framework.Graphics.Texture2D>";
    private const string TextureGenericArg = "global::Microsoft.Xna.Framework.Graphics.Texture2D";

    private const string EffectType = "global::ReLogic.Content.Asset<global::Microsoft.Xna.Framework.Graphics.Effect>";
    private const string EffectGenericArg = "global::Microsoft.Xna.Framework.Graphics.Effect";

    private const string FontType = "global::ReLogic.Content.Asset<global::ReLogic.Graphics.DynamicSpriteFont>";
    private const string FontGenericArg = "global::ReLogic.Graphics.DynamicSpriteFont";

    private const string SoundType = "global::Terraria.Audio.SoundStyle";

    private sealed class TreeNode
    {
        public string RawName { get; }
        public Dictionary<string, TreeNode> Children { get; } = new(StringComparer.OrdinalIgnoreCase);
        public List<AssetRecord> Assets { get; } = new();

        public TreeNode(string rawName)
        {
            RawName = rawName;
        }
    }

    public static string Emit(string rootNamespace, EquatableArray<AssetRecord> records)
    {
        string ns = string.IsNullOrWhiteSpace(rootNamespace) ? "Apotheosis" : rootNamespace;
        var root = BuildTree(DeduplicateRecords(records));

        var sb = new StringBuilder(4096);
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.Append("namespace ").AppendLine(ns);
        sb.AppendLine("{");

        EmitClassNode(sb, root, AssetGeneratorConfig.RootClassName, indentLevel: 1, isRoot: true);

        sb.AppendLine();
        sb.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.AppendLine("    internal sealed class AssetsUnloader : global::Terraria.ModLoader.ILoadable");
        sb.AppendLine("    {");
        sb.AppendLine("        public void Load(global::Terraria.ModLoader.Mod mod) { }");
        sb.AppendLine();
        sb.Append("        public void Unload() => ").Append(AssetGeneratorConfig.RootClassName).AppendLine(".UnloadAll();");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        return sb.ToString();
    }

    private static List<AssetRecord> DeduplicateRecords(EquatableArray<AssetRecord> records)
    {
        // 对具有相同 (ModAssetPath, Kind) 的资源去重，例如 Foo.png 与 Foo.rawimg。
        var bestByKey = new Dictionary<(string Path, AssetKind Kind), AssetRecord>();

        for (int i = 0; i < records.Length; i++)
        {
            var record = records[i];
            var key = (record.ModAssetPath.ToLowerInvariant(), record.Kind);

            if (!bestByKey.TryGetValue(key, out var existing))
            {
                bestByKey[key] = record;
            }
            else
            {
                int newPrio = AssetPathResolver.GetExtensionPriority(record.Extension);
                int oldPrio = AssetPathResolver.GetExtensionPriority(existing.Extension);
                if (newPrio < oldPrio
                    || (newPrio == oldPrio && string.CompareOrdinal(record.RelativeFilePath, existing.RelativeFilePath) < 0))
                {
                    bestByKey[key] = record;
                }
            }
        }

        return bestByKey.Values
            .OrderBy(static r => r.RelativeFilePath, StringComparer.OrdinalIgnoreCase)
            .ThenBy(static r => r.RelativeFilePath, StringComparer.Ordinal)
            .ToList();
    }

    private static TreeNode BuildTree(List<AssetRecord> records)
    {
        var root = new TreeNode(AssetGeneratorConfig.RootClassName);

        for (int i = 0; i < records.Count; i++)
        {
            var record = records[i];
            var current = root;

            var dirs = record.DirectorySegments;
            for (int d = 0; d < dirs.Length; d++)
            {
                string segment = dirs[d];
                if (!current.Children.TryGetValue(segment, out var child))
                {
                    child = new TreeNode(segment);
                    current.Children[segment] = child;
                }

                current = child;
            }

            current.Assets.Add(record);
        }

        return root;
    }

    private static void EmitClassNode(
        StringBuilder sb,
        TreeNode node,
        string classIdentifierCore,
        int indentLevel,
        bool isRoot)
    {
        string indent = new string(' ', indentLevel * 4);
        string memberIndent = new string(' ', (indentLevel + 1) * 4);
        string classIdentifier = AssetPathResolver.EscapeIfKeyword(classIdentifierCore);

        sb.Append(indent).Append("public static partial class ").AppendLine(classIdentifier);
        sb.Append(indent).AppendLine("{");

        // 记录当前类中所有已占用的成员名称（未转义核心名），确保零编译冲突。
        var usedMembers = new HashSet<string>(StringComparer.Ordinal)
        {
            classIdentifierCore, // 防止 CS0542：成员名称不能与外层封闭类型相同
            "__Unload",
        };
        if (isRoot)
        {
            usedMembers.Add("UnloadAll");
        }

        // 1. 按确定性顺序解析子嵌套类名。
        var orderedChildren = node.Children.Values
            .OrderBy(static c => c.RawName, StringComparer.OrdinalIgnoreCase)
            .ThenBy(static c => c.RawName, StringComparer.Ordinal)
            .ToList();

        var resolvedChildren = new List<(TreeNode Node, string ClassCore)>(orderedChildren.Count);
        for (int i = 0; i < orderedChildren.Count; i++)
        {
            var child = orderedChildren[i];
            string baseCore = AssetPathResolver.SanitizeIdentifierCore(child.RawName);
            string candidate = baseCore;
            if (!usedMembers.Add(candidate))
            {
                candidate = baseCore + "_Dir";
                int suffix = 2;
                while (!usedMembers.Add(candidate))
                {
                    candidate = baseCore + "_Dir" + suffix;
                    suffix++;
                }
            }

            resolvedChildren.Add((child, candidate));
        }

        // 2. 按确定性顺序解析资源属性名与后备字段名。
        var orderedAssets = node.Assets
            .OrderBy(static a => a.FileNameWithoutExtension, StringComparer.OrdinalIgnoreCase)
            .ThenBy(static a => a.Kind)
            .ThenBy(static a => a.RelativeFilePath, StringComparer.Ordinal)
            .ToList();

        // 统计基础名称出现次数，用于检测同名冲突（不同资源类型或因跳过目录导致提升冲突）。
        var baseNameCounts = new Dictionary<string, int>(StringComparer.Ordinal);
        var baseNameKinds = new Dictionary<string, HashSet<AssetKind>>(StringComparer.Ordinal);
        for (int i = 0; i < orderedAssets.Count; i++)
        {
            string baseCore = AssetPathResolver.SanitizeIdentifierCore(orderedAssets[i].FileNameWithoutExtension);
            baseNameCounts.TryGetValue(baseCore, out int count);
            baseNameCounts[baseCore] = count + 1;

            if (!baseNameKinds.TryGetValue(baseCore, out var kindSet))
            {
                kindSet = new HashSet<AssetKind>();
                baseNameKinds[baseCore] = kindSet;
            }

            kindSet.Add(orderedAssets[i].Kind);
        }

        var backingFieldNames = new List<string>(orderedAssets.Count);

        for (int i = 0; i < orderedAssets.Count; i++)
        {
            var asset = orderedAssets[i];
            string baseCore = AssetPathResolver.SanitizeIdentifierCore(asset.FileNameWithoutExtension);
            string propCore = ResolveAssetPropertyCore(
                asset,
                baseCore,
                baseNameCounts[baseCore] > 1,
                baseNameKinds[baseCore].Count > 1,
                usedMembers);

            string pathConstCore = propCore + "Path";
            string fieldCore = ResolveBackingFieldCore(propCore, usedMembers);
            backingFieldNames.Add(fieldCore);

            if (i > 0)
                sb.AppendLine();

            EmitAssetMembers(sb, memberIndent, asset, propCore, pathConstCore, fieldCore);
        }

        // 3. 生成子嵌套类。
        for (int i = 0; i < resolvedChildren.Count; i++)
        {
            if (orderedAssets.Count > 0 || i > 0)
                sb.AppendLine();

            var (childNode, childClassCore) = resolvedChildren[i];
            EmitClassNode(sb, childNode, childClassCore, indentLevel + 1, isRoot: false);
        }

        // 4. 生成卸载清理方法。
        if (orderedAssets.Count > 0 || resolvedChildren.Count > 0)
            sb.AppendLine();

        if (isRoot)
        {
            sb.Append(memberIndent).AppendLine("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
            sb.Append(memberIndent).AppendLine("internal static void UnloadAll() => __Unload();");
            sb.AppendLine();
        }

        sb.Append(memberIndent).AppendLine("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.Append(memberIndent).AppendLine("internal static void __Unload()");
        sb.Append(memberIndent).AppendLine("{");

        string bodyIndent = new string(' ', (indentLevel + 2) * 4);
        for (int i = 0; i < backingFieldNames.Count; i++)
        {
            sb.Append(bodyIndent).Append(backingFieldNames[i]).AppendLine(" = null;");
        }

        for (int i = 0; i < resolvedChildren.Count; i++)
        {
            string childClass = AssetPathResolver.EscapeIfKeyword(resolvedChildren[i].ClassCore);
            sb.Append(bodyIndent).Append(childClass).AppendLine(".__Unload();");
        }

        sb.Append(memberIndent).AppendLine("}");
        sb.Append(indent).AppendLine("}");
    }

    private static string ResolveAssetPropertyCore(
        AssetRecord asset,
        string baseCore,
        bool hasDuplicateBaseName,
        bool hasMultipleKindsForBaseName,
        HashSet<string> usedMembers)
    {
        var candidates = new List<string>(4);

        if (!hasDuplicateBaseName)
        {
            candidates.Add(baseCore);
        }
        else
        {
            // 若不同资源类型共享相同基础名（例如 Hit.png 与 Hit.ogg），优先追加类型后缀。
            if (hasMultipleKindsForBaseName)
            {
                candidates.Add(baseCore + "_" + AssetPathResolver.GetKindSuffix(asset.Kind));
            }

            // 若从被跳过的目录提升而来，优先使用最近的被跳过父目录段作为前缀。
            if (asset.SkippedSegments.Length > 0)
            {
                var skippedPrefix = new StringBuilder();
                for (int s = asset.SkippedSegments.Length - 1; s >= 0; s--)
                {
                    string seg = AssetPathResolver.SanitizeIdentifierCore(asset.SkippedSegments[s]);
                    if (skippedPrefix.Length == 0)
                        skippedPrefix.Append(seg);
                    else
                        skippedPrefix.Insert(0, seg + "_");

                    string hoistedCandidate = skippedPrefix + "_" + baseCore;
                    candidates.Add(hoistedCandidate);
                    if (hasMultipleKindsForBaseName)
                        candidates.Add(hoistedCandidate + "_" + AssetPathResolver.GetKindSuffix(asset.Kind));
                }
            }

            candidates.Add(baseCore);
        }

        // 当 baseCore 与外层类或子嵌套类冲突时，始终允许使用类型后缀作为兜底名称。
        candidates.Add(baseCore + "_" + AssetPathResolver.GetKindSuffix(asset.Kind));

        for (int i = 0; i < candidates.Count; i++)
        {
            string candidate = candidates[i];
            if (TryReservePropertyPair(candidate, usedMembers))
                return candidate;
        }

        int index = 2;
        while (true)
        {
            string fallback = baseCore + "_" + index;
            if (TryReservePropertyPair(fallback, usedMembers))
                return fallback;
            index++;
        }
    }

    private static bool TryReservePropertyPair(string propCore, HashSet<string> usedMembers)
    {
        string pathConstCore = propCore + "Path";
        if (usedMembers.Contains(propCore) || usedMembers.Contains(pathConstCore))
            return false;

        usedMembers.Add(propCore);
        usedMembers.Add(pathConstCore);
        return true;
    }

    private static string ResolveBackingFieldCore(string propCore, HashSet<string> usedMembers)
    {
        string baseField = propCore.Length > 0
            ? "_" + char.ToLowerInvariant(propCore[0]) + propCore.Substring(1)
            : "_asset";

        string candidate = baseField;
        int index = 2;
        while (!usedMembers.Add(candidate))
        {
            candidate = baseField + "_" + index;
            index++;
        }

        return candidate;
    }

    private static void EmitAssetMembers(
        StringBuilder sb,
        string indent,
        AssetRecord asset,
        string propCore,
        string pathConstCore,
        string fieldCore)
    {
        string propName = AssetPathResolver.EscapeIfKeyword(propCore);
        string pathConstName = AssetPathResolver.EscapeIfKeyword(pathConstCore);
        string escapedPathLiteral = EscapeStringLiteral(asset.ModAssetPath);
        string xmlSafePath = EscapeXml(asset.ModAssetPath);

        sb.Append(indent).Append("/// <summary>资源路径：<c>").Append(xmlSafePath).AppendLine("</c></summary>");
        sb.Append(indent).Append("public const string ").Append(pathConstName)
          .Append(" = \"").Append(escapedPathLiteral).AppendLine("\";");

        string propType;
        string initExpression;
        string kindDesc;

        switch (asset.Kind)
        {
            case AssetKind.Texture:
                propType = TextureType;
                initExpression = $"global::Terraria.ModLoader.ModContent.Request<{TextureGenericArg}>({pathConstName})";
                kindDesc = "贴图";
                break;

            case AssetKind.Effect:
                propType = EffectType;
                initExpression = $"global::Terraria.ModLoader.ModContent.Request<{EffectGenericArg}>({pathConstName})";
                kindDesc = "着色器";
                break;

            case AssetKind.Font:
                propType = FontType;
                initExpression = $"global::Terraria.ModLoader.ModContent.Request<{FontGenericArg}>({pathConstName})";
                kindDesc = "字体";
                break;

            case AssetKind.Sound:
                propType = SoundType;
                initExpression = $"new {SoundType}({pathConstName})";
                kindDesc = "音效";
                break;

            default:
                throw new ArgumentOutOfRangeException();
        }

        sb.Append(indent).Append("private static ").Append(propType).Append("? ").Append(fieldCore).AppendLine(";");
        sb.Append(indent).Append("/// <summary>懒加载").Append(kindDesc).Append("资源：<c>").Append(xmlSafePath).AppendLine("</c></summary>");
        sb.Append(indent).Append("public static ").Append(propType).Append(' ').Append(propName)
          .Append(" => ").Append(fieldCore).Append(" ??= ").Append(initExpression).AppendLine(";");
    }

    private static string EscapeStringLiteral(string value)
    {
        return value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"");
    }

    private static string EscapeXml(string value)
    {
        return value
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }
}
